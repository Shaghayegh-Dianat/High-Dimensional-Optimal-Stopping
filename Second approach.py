import tensorflow as tf
from tensorflow.python.training.moving_averages import assign_moving_average
import numpy as np
import time
from tensorflow.python.framework.ops import disable_eager_execution

disable_eager_execution()
print(tf.config.list_physical_devices('GPU'))

T, N, K = 3., 9, 100.
r, delta, sigma = 0.05, 0.1, 0.2
batch_size = 8192
lr_values = [0.05, 0.005, 0.0005]
mc_runs = 10000
def neural_net(x, neurons, is_training, dtype=tf.float32, decay=0.9):
    def batch_normalization(y):
        shape = y.get_shape().as_list()
        y = tf.reshape(y, [-1, shape[1] * shape[2]])
        beta = tf.compat.v1.get_variable(
            name='beta', shape=[shape[1] * shape[2]],
            dtype=dtype, initializer=tf.zeros_initializer())
        gamma = tf.compat.v1.get_variable(
            name='gamma', shape=[shape[1] * shape[2]],
            dtype=dtype, initializer=tf.ones_initializer())
        mv_mean = tf.compat.v1.get_variable(
            'mv_mean', [shape[1] * shape[2]],
            dtype=dtype, initializer=tf.zeros_initializer(),
            trainable=False)
        mv_var = tf.compat.v1.get_variable(
            'mv_var', [shape[1] * shape[2]],
            dtype=dtype, initializer=tf.ones_initializer(),
            trainable=False)
        mean, variance = tf.nn.moments(y, [0], name='moments')
        tf.compat.v1.add_to_collection(
            tf.compat.v1.GraphKeys.UPDATE_OPS,
            assign_moving_average(mv_mean, mean, decay,
                                  zero_debias=True))
        tf.compat.v1.add_to_collection(
            tf.compat.v1.GraphKeys.UPDATE_OPS,
            assign_moving_average(mv_var, variance, decay,
                                  zero_debias=False))
        mean, variance = tf.cond(is_training, lambda: (mean, variance),
                                 lambda: (mv_mean, mv_var))
        y = tf.nn.batch_normalization(y, mean, variance, beta, gamma, 1e-6)
        return tf.reshape(y, [-1, shape[1], shape[2]])
# Applies batch normalization to a three-dimensional tensor with shape
# [batch_size, num_features, num_time_steps].
# First, the feature and time dimensions are flattened so that the
# mean and variance can be computed across the batch dimension.
# Standard normalization is then applied using the learnable
# scale (gamma) and offset (beta) parameters.
# During training, batch statistics are computed and accumulated
# in the moving variables using exponential moving averages.
# During evaluation, the stored moving statistics are used instead
# of the statistics of the current batch to ensure stable behavior.
# Finally, the output is reshaped to its original dimensions:
# [batch_size, num_features, num_time_steps].

    def fc_layer(y, out_size, activation, is_single):
        shape = y.get_shape().as_list()
        w = tf.compat.v1.get_variable(
            name='weights',
            shape=[shape[2], shape[1], out_size],
            dtype=dtype,
            initializer=tf.initializers.glorot_uniform())
        y = tf.transpose(tf.matmul(tf.transpose(y, [2, 0, 1]), w),
                         [1, 2, 0])
        if is_single:
            b = tf.compat.v1.get_variable(
                name='bias',
                shape=[out_size, shape[2]],
                dtype=dtype,
                initializer=tf.zeros_initializer())
            return activation(y + b)
        return activation(batch_normalization(y))

    x = batch_normalization(x)
    for i in range(len(neurons)):
        with tf.compat.v1.variable_scope('layer_' + str(i)):
            x = fc_layer(x, neurons[i],
                         tf.nn.relu if i < len(neurons) - 1
                         else tf.nn.sigmoid, False)
    return x

# Applies a time-dependent fully connected layer to a three-dimensional
# tensor with shape [batch_size, num_features, num_time_steps].
# An independent weight matrix is used at each time step; the weight
# tensor has shape [num_time_steps, num_features, out_size]. However,
# the complete layer is trained as part of a single global network
# using one objective function.
# Matrix multiplication is performed separately at each time step,
# producing an output with shape [batch_size, out_size, num_time_steps].
# When batch normalization is used, a separate bias is omitted and
# the activation function is applied after batch normalization.

def deep_optimal_stopping(x, t, n, g, neurons, batch_size, train_steps,
                          mc_runs, lr_boundaries, lr_values, beta1=0.9,
                          beta2=0.999, epsilon=1e-8, decay=0.9):
    is_training = tf.compat.v1.placeholder(tf.bool, [])
    p = g(t, x)
    nets = neural_net(tf.concat([x[:, :, :-1], p[:, :, :-1]], axis=1),
                      neurons, is_training, decay=decay)

    u_list = [nets[:, :, 0]]
    u_sum = u_list[-1]
    for k in range(1, n - 1):
        u_list.append(nets[:, :, k] * (1. - u_sum))
        u_sum += u_list[-1]

    u_list.append(1. - u_sum)
    u_stack = tf.concat(u_list, axis=1)
    p = tf.squeeze(p, axis=1)
    loss = tf.reduce_mean(tf.reduce_sum(-u_stack * p, axis=1))
    idx = tf.argmax(tf.cast(tf.cumsum(u_stack, axis=1) + u_stack >= 1,
                            dtype=tf.uint8),
                    axis=1, output_type=tf.int32)
    stopped_payoffs_pathwise = tf.gather_nd(
    p, tf.stack([tf.range(0, batch_size, dtype=tf.int32), idx], axis=1)
)
    stopped_payoffs = tf.reduce_mean(stopped_payoffs_pathwise)


    global_step = tf.Variable(0)
    learning_rate = tf.compat.v1.train.piecewise_constant(global_step,
                                                          lr_boundaries,
                                                          lr_values)
    optimizer = tf.compat.v1.train.AdamOptimizer(learning_rate,
                                                 beta1=beta1,
                                                 beta2=beta2,
                                                 epsilon=epsilon)
    update_ops = tf.compat.v1.get_collection(
        tf.compat.v1.GraphKeys.UPDATE_OPS)
    with tf.control_dependencies(update_ops):
        train_op = optimizer.minimize(loss, global_step=global_step)

    with tf.compat.v1.Session() as sess:

        sess.run(tf.compat.v1.global_variables_initializer())

        for _ in range(train_steps):
            sess.run(train_op, feed_dict={is_training: True})

        test_paths = 10000
        payoffs = []
        while len(payoffs) < test_paths:
            batch_payoffs = sess.run(stopped_payoffs_pathwise,
                             feed_dict={is_training: False})
            payoffs.append(batch_payoffs)
        payoffs = np.concatenate(payoffs, axis=0)[:test_paths]
        return float(np.mean(payoffs))


# Implements a deep-learning approach to the optimal stopping problem.
# The neural network defines a global randomized stopping policy over
# the time grid, and its parameters are trained by maximizing the
# expected weighted payoff.
# The network's soft outputs are converted into a probability
# distribution over the possible stopping times. A hard stopping
# time is then extracted, and the corresponding payoff is estimated
# using Monte Carlo averaging.
# The entire model is trained jointly with a single objective function
# and a gradient-based optimization method.
def g(s, x):
    return tf.exp(-r * s) \
           * tf.maximum(tf.reduce_max(x, axis=1, keepdims=True) - K, 0.)


_file = open("bermudan_max_call_global.csv", 'w')
_file.write('dim, s0, run, mean, time\n')
_file.flush()

for d in [10,50,100,200,500,1000]:
    for s_0 in [90., 100., 110.]:
        vals, times = [], []

        for run in range(10):
            tf.compat.v1.reset_default_graph()
            t0 = time.time()

            neurons = [d + 50, d + 50, 1]
            train_steps = 1500 + d
            lr_boundaries = [int(500 + d / 5), int(1500 + 3 * d / 5)]

            W = tf.cumsum(tf.compat.v1.random_normal(
                shape=[batch_size, d, N],
                stddev=np.sqrt(T / N)), axis=2)

            t = tf.constant(np.linspace(start=T / N, stop=T, num=N,
                                        endpoint=True, dtype=np.float32))

            X = tf.exp((r - delta - sigma ** 2 / 2.) * t + sigma * W) * s_0

            px_mean = deep_optimal_stopping(
                X, t, N, g, neurons, batch_size,
                train_steps, mc_runs,
                lr_boundaries, lr_values, epsilon=0.1)

            t1 = time.time()
            elapsed = t1 - t0

            vals.append(px_mean)
            times.append(elapsed)

            print(f"dim={d}, s0={s_0}, run={run+1}, mean={px_mean:.4f}, time={elapsed:.2f}s")

            _file.write('%i, %.1f, %i, %.4f, %.2f\n' % (d, s_0, run+1, px_mean, elapsed))
            _file.flush()


        print(f"SUMMARY d={d}, s0={s_0}: std={np.std(vals):.4f}, total_time={sum(times):.2f}s")
        _file.write(f"SUMMARY,{d},{s_0},{np.std(vals):.4f},{sum(times):.2f}\n")
        _file.flush()

_file.close()