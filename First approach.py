            F[N] = FN; f[N] = fN; l[N] = lN

            # --- simulate training paths ---
            X = GBM(d, mu, sigma, S0, T, dt, total_paths, seed=seed_train_run)
            X = X.reshape(number_of_training_steps, batch_size, d, N + 1)

            # --- training ---
            start_time = time.time()
            for i in range(N-1, 0, -1):
                model = create_model(d).to(device)
                optimizer = torch.optim.Adam(model.parameters(), lr=learning_rate)
                train(X, r, k, dt, model, i, optimizer,
                      number_of_training_steps, batch_size)
                F[i] = model
                f[i] = lambda x, i=i: fi(x, i, F)
                l[i] = lambda x, i=i: li(x, i, f, l)

            elapsed_time = time.time() - start_time


            X_test = GBM(d, mu, sigma, S0, T, dt, test_paths, seed=seed_test_run)
            g_val = g(X_test, r, k, dt)
